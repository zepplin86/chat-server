//! 순번 매기기.
//!
//! 5단계까지는 DB 가 순번을 매겼다. 메시지를 넣으면 DB 가 1, 2, 3... 을 붙여 돌려줬다.
//! 이제 채팅 서버는 말하기에서 DB 를 기다리지 않는다. 그러면 DB 에게 순번을 받을 수도 없다.
//! 그래서 채팅 서버가 직접 매긴다.
//!
//! 순번이 지켜야 할 것은 두 가지다. 겹치지 않을 것, 나중 것이 더 클 것.
//! 지금 시각이 이 둘을 거의 다 채워 준다. 시간은 앞으로만 가기 때문이다.
//!
//!   순번 = 1970년부터 지금까지의 밀리초 × 1000
//!
//! 같은 밀리초에 두 개가 오면 겹치므로, 그때는 직전 순번에 1 을 더한다. (× 1000 이 그 자리를 비워 둔 것이다)
//! 예: 1763611200000000, 1763611200000001, 1763611200001000, ...
//!
//! 서버를 껐다 켜도 시각은 그사이 흘렀으므로 예전 순번보다 크다. 어디에 적어 둘 필요가 없다.
use std::sync::Mutex;
use std::time::{SystemTime, UNIX_EPOCH};

/// 순번을 매기는 것. 채팅 서버에 하나만 둔다.
pub struct SeqMaker {
    /// 마지막으로 내준 순번.
    /// Mutex 는 한 번에 하나만 들어갈 수 있는 자물쇠다. 요청 여럿이 동시에 와도 한 줄로 서서 받아 간다.
    last: Mutex<i64>,
}

impl SeqMaker {
    pub fn new() -> Self {
        Self { last: Mutex::new(0) }
    }

    /// 다음 순번을 내준다. 부를 때마다 직전보다 큰 수가 나온다.
    pub fn next(&self) -> i64 {
        let millis = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .expect("컴퓨터의 시계가 1970년보다 앞이다")
            .as_millis() as i64;
        let mut last = self.last.lock().expect("순번 자물쇠가 망가졌다");
        // 지금 시각으로 만든 수와 "직전 순번 + 1" 중 큰 쪽을 쓴다.
        // 같은 밀리초에 또 왔거나 시계가 뒤로 갔어도 직전보다 커진다.
        *last = (millis * 1000).max(*last + 1);
        *last
    }
}
